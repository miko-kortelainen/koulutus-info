package main

import (
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"school-api/services"
	"sort"
	"strconv"
	"strings"
)

const toinenAsteURL = "https://api.vipunen.fi/api/resources/perusopetuksen_jalkeinen_koulutus_hakeneet_ja_paikan_vastaanottaneet/data"
const toinenAsteDir = dataOutputDir + "/toinen-aste"
const toinenAsteManifest = "../frontend/src/generated/toinenAsteYears.ts"

var toinenAsteFilename = regexp.MustCompile(`^hakijamaarat-(\d{4})\.json$`)

type toinenAsteRow struct {
	Haku                    string `json:"haku,omitempty"`
	KooditHakukohde         string `json:"kooditHakukohde"`
	KooditTutkintoHakukohde string `json:"kooditTutkintoHakukohde"`
	Hakukohde               string `json:"hakukohde"`
	Oppilaitos              string `json:"oppilaitos"`
	KuntaHakukohde          string `json:"kuntaHakukohde"`
	KoulutusasteTaso2       string `json:"koulutusasteTaso2"`
	KoulutusalaTaso1        string `json:"koulutusalaTaso1"`
	KoulutuksenKieli        string `json:"koulutuksenKieli"`
	AloituspaikatLkm        int    `json:"aloituspaikatLkm"`
	KaikkiHakijatLkm        int    `json:"kaikkiHakijatLkm"`
	EnsisijaisetHakijatLkm  int    `json:"ensisijaisetHakijatLkm"`
	ValitutLkm              int    `json:"valitutLkm"`
}

func filterToinenAste(rows []toinenAsteRow) ([]toinenAsteRow, bool) {
	result := make([]toinenAsteRow, 0, len(rows))
	hasApplicants := false
	for _, row := range rows {
		if row.Haku != "Perusopetuksen jälkeisen koulutuksen yhteishaku" && row.Haku != "Ammatillisen koulutuksen ja lukiokoulutuksen yhteishaku" {
			continue
		}
		if row.KooditHakukohde == "1.2.246.562.20.00000000000000087412" || row.KooditHakukohde == "1.2.246.562.20.00000000000000083894" {
			continue
		}
		if row.KaikkiHakijatLkm > 0 {
			hasApplicants = true
		}
		row.Haku = ""
		result = append(result, row)
	}
	return result, hasApplicants
}

func generateToinenAste(year int) error {
	params := url.Values{"filter": {fmt.Sprintf("koulutuksenAlkamisvuosi=='%d'", year)}, "limit": {"100000"}}
	var rows []toinenAsteRow
	if err := services.FetchJSON("Vipunen toinen aste", toinenAsteURL+"?"+params.Encode(), &rows); err != nil {
		return err
	}
	if len(rows) >= 100000 {
		return fmt.Errorf("Vipunen toinen aste returned too many rows")
	}
	data, hasApplicants := filterToinenAste(rows)
	if !hasApplicants {
		fmt.Printf("Vipunen toinen aste: no published applicant counts for %d\n", year)
		return writeToinenAsteManifest(toinenAsteDir, toinenAsteManifest)
	}
	path := filepath.Join(toinenAsteDir, fmt.Sprintf("hakijamaarat-%d.json", year))
	if err := validateRecordCount(path, len(data), "Vipunen toinen aste"); err != nil {
		return err
	}
	changed, err := jsonChanged(path, data)
	if err != nil {
		return err
	}
	if changed {
		if err := writeJSON(path, data); err != nil {
			return err
		}
	}
	fmt.Printf("Vipunen toinen aste: year=%d records=%d changed=%t\n", year, len(data), changed)
	return writeToinenAsteManifest(toinenAsteDir, toinenAsteManifest)
}

func writeToinenAsteManifest(dir, path string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	years := []string{}
	for _, entry := range entries {
		if !entry.IsDir() {
			if match := toinenAsteFilename.FindStringSubmatch(entry.Name()); match != nil {
				years = append(years, match[1])
			}
		}
	}
	if len(years) == 0 {
		return fmt.Errorf("no second-degree applicant statistics found")
	}
	sort.Sort(sort.Reverse(sort.StringSlice(years)))
	quoted := make([]string, len(years))
	for i, year := range years {
		quoted[i] = strconv.Quote(year)
	}
	content := fmt.Sprintf("// Generated by the data generator. Do not edit manually.\nexport const TOINEN_ASTE_YEARS = [%s] as const;\n", strings.Join(quoted, ", "))
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0644)
}
