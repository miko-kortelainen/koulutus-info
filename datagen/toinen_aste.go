package main

import (
	"datagen/services"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const toinenAsteDir = dataOutputDir + "/toinen-aste"
const toinenAsteManifest = "../frontend/src/generated/toinenAsteYears.ts"

var toinenAsteFilename = regexp.MustCompile(`^hakijamaarat-(\d{4})\.json$`)

func generateToinenAste(year int) error {
	data, hasApplicants, err := services.FetchToinenAste(year)
	if err != nil {
		return err
	}
	if !hasApplicants {
		fmt.Printf("Vipunen toinen aste: no published applicant counts for %d\n", year)
		return writeToinenAsteManifest(toinenAsteDir, toinenAsteManifest)
	}
	path := filepath.Join(toinenAsteDir, fmt.Sprintf("hakijamaarat-%d.json", year))
	if err := validateRecordCount(path, len(data), "Vipunen toinen aste"); err != nil {
		return err
	}
	changed, err := jsonChanged(path, data)
	if err != nil {
		return err
	}
	if changed {
		if err := writeJSON(path, data); err != nil {
			return err
		}
	}
	fmt.Printf("Vipunen toinen aste: year=%d records=%d changed=%t\n", year, len(data), changed)
	return writeToinenAsteManifest(toinenAsteDir, toinenAsteManifest)
}

func writeToinenAsteManifest(dir, path string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	years := []string{}
	for _, entry := range entries {
		if !entry.IsDir() {
			if match := toinenAsteFilename.FindStringSubmatch(entry.Name()); match != nil {
				years = append(years, match[1])
			}
		}
	}
	if len(years) == 0 {
		return fmt.Errorf("no second-degree applicant statistics found")
	}
	sort.Sort(sort.Reverse(sort.StringSlice(years)))
	quoted := make([]string, len(years))
	for i, year := range years {
		quoted[i] = strconv.Quote(year)
	}
	content := fmt.Sprintf("// Generated by the data generator. Do not edit manually.\nexport const TOINEN_ASTE_YEARS = [%s] as const;\n", strings.Join(quoted, ", "))
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0644)
}
